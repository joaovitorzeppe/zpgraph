/**
 * Sync src/style.css → src/style-text.ts for runtime CSS injection
 * (ensureZpgraphStyles). dist/style.css is copied by tsdown `copy`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "src/style.css"), "utf8");

writeFileSync(
  join(root, "src/style-text.ts"),
  `/**
 * @license
 * Copyright (c) 2026 João Vitor Zeppe (zeppejoaovitor@gmail.com)
 * MIT-licensed: https://opensource.org/license/MIT
 */

/** Injected stylesheet text — generated by scripts/gen-style-text.mjs. Do not edit. */
export const ZPGRAPH_CSS: string = ${JSON.stringify(css)};
`,
  "utf8",
);

console.log("synced style.css → src/style-text.ts");
